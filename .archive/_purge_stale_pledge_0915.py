def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


def save(p: Path, obj):
    _ind = 2 if p.name in ("dashboard_decisions.json", "pending_decisions.json", "schedule_events.json") else 1
    p.write_text(json.dumps(obj, ensure_ascii=False, indent=_ind), encoding="utf-8")


def apply_all(node, path=""):
    """遞迴：字串完全相符 or 子字串替換"""

    def fix_s(s: str) -> str:
        for old, new, _sub in PAIRS:
            if s == old:
                LOG.append(f"  等值替換 {path}")
                return new
            if old in s:
                LOG.append(f"  子字串替換 {path}")
                s = s.replace(old, new)
        return s

    if isinstance(node, dict):
        return {k: apply_all(v, f"{path}.{k}") for k, v in node.items()}
    if isinstance(node, list):
        return [apply_all(v, f"{path}[{i}]") for i, v in enumerate(node)]
    if isinstance(node, str):
        return fix_s(node)
    return node


def process(name: str, expected_len: bool = True):
    p = BASE / name
    before = load(p)
    after = apply_all(before)
    if json.dumps(before, ensure_ascii=False) == json.dumps(after, ensure_ascii=False):
        print(f"ℹ️ {name}：無變更")
        return 0
    shutil.copy2(p, BASE / f"{name}.bak-0915purge")
    save(p, after)
    chk = load(p)
    if isinstance(before, list):
        assert len(chk) == len(before), f"{name} 筆數變動！"
    else:
        assert set(chk.keys()) == set(before.keys()), f"{name} 頂層鍵變動！"
    print(f"✅ {name}：已更新（備份 {name}.bak-0915purge）")
    return 1


